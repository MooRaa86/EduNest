-- =====================================================================
-- Migration V8: Failed Email Attempts Observability & Retry Store (EB-62 / INT-02)
-- Purpose: Outbox-style persistence for failed SMTP deliveries, bounded retries,
--          and administrative visibility/action.
-- Dialect: PostgreSQL 17.x
-- =====================================================================

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS failed_email_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID DEFAULT gen_random_uuid() NOT NULL,
    recipient VARCHAR(255) NOT NULL,
    subject VARCHAR(255) NOT NULL,
    html_body TEXT NOT NULL,
    attempt_count INT NOT NULL DEFAULT 1,
    max_attempts INT NOT NULL DEFAULT 3,
    last_error TEXT,
    status VARCHAR(32) NOT NULL DEFAULT 'PENDING',
    created_at TIMESTAMP(6) NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMP(6) NOT NULL DEFAULT NOW(),
    created_by VARCHAR(255) NOT NULL DEFAULT 'SYSTEM',
    updated_by VARCHAR(255) NOT NULL DEFAULT 'SYSTEM',
    last_attempt_at TIMESTAMP(6) NOT NULL DEFAULT NOW(),
    next_retry_at TIMESTAMP(6),
    resolved_at TIMESTAMP(6),
    resolved_by VARCHAR(255)
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_fea_public_id ON failed_email_attempts(public_id);
CREATE INDEX IF NOT EXISTS idx_fea_status_next_retry ON failed_email_attempts(status, next_retry_at);
CREATE INDEX IF NOT EXISTS idx_fea_recipient ON failed_email_attempts(recipient);
CREATE INDEX IF NOT EXISTS idx_fea_created_at ON failed_email_attempts(created_at);
