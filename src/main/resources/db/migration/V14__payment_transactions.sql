-- =====================================================================
-- Migration V13: Payment Transactions — Stripe Enrollment Payments (EB-108)
-- Purpose: D-28 / P4-18 — one row per Stripe Checkout Session created for a
--          mentorship join attempt. Webhook is the sole source of truth for
--          PAID; unique stripe_session_id is the schema-level idempotency
--          backstop. Amount/currency are server-side snapshots captured at
--          session creation (never client input).
-- Decisions pinned by code (Omar, 2026-11-12):
--   C: STRIPE_ENABLED=false keeps legacy free-join (no rows here)
--   E: currency USD only
--   F: refunds/disputes are record-only; enrollment access stays
--   Free Tier Bypass: amount==0 joins never create a transaction (no Stripe)
-- Dialect: PostgreSQL 17.x
-- =====================================================================

CREATE TABLE IF NOT EXISTS payment_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID DEFAULT gen_random_uuid() NOT NULL,
    amount double precision NOT NULL,
    currency varchar(3) NOT NULL DEFAULT 'USD',
    status varchar(32) NOT NULL DEFAULT 'PENDING',
    stripe_session_id varchar(255) NOT NULL,
    stripe_payment_intent_id varchar(255),
    paid_at timestamp(6),
    terminal_reason varchar(255),
    mentorship_id bigint NOT NULL,
    student_id bigint NOT NULL,
    created_at timestamp(6) NOT NULL DEFAULT now(),
    updated_at timestamp(6) NOT NULL DEFAULT now(),
    created_by varchar(255) NOT NULL DEFAULT 'SYSTEM',
    updated_by varchar(255) NOT NULL DEFAULT 'SYSTEM'
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_payment_tx_stripe_session
    ON payment_transactions (stripe_session_id);
CREATE UNIQUE INDEX IF NOT EXISTS idx_payment_tx_public_id
    ON payment_transactions (public_id);
CREATE INDEX IF NOT EXISTS idx_payment_tx_student
    ON payment_transactions (student_id);
CREATE INDEX IF NOT EXISTS idx_payment_tx_mentorship
    ON payment_transactions (mentorship_id);
CREATE INDEX IF NOT EXISTS idx_payment_tx_status
    ON payment_transactions (status);
CREATE INDEX IF NOT EXISTS idx_payment_tx_payment_intent
    ON payment_transactions (stripe_payment_intent_id);

-- FKs: no cascade (financial records must not die with the referenced rows —
-- same posture as enrollments in V1).
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'fk_payment_tx_mentorship'
    ) THEN
        ALTER TABLE payment_transactions
            ADD CONSTRAINT fk_payment_tx_mentorship
            FOREIGN KEY (mentorship_id) REFERENCES mentorship;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'fk_payment_tx_student'
    ) THEN
        ALTER TABLE payment_transactions
            ADD CONSTRAINT fk_payment_tx_student
            FOREIGN KEY (student_id) REFERENCES students;
    END IF;
END $$;
