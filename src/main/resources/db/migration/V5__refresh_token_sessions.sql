-- =====================================================================
-- Migration V5: Refresh Token Sessions & Revocation Store (EB-91)
-- Purpose: Persistent session management, rotating refresh tokens,
--          strict replay detection, and session revocation infrastructure.
-- Dialect: PostgreSQL 17.x
-- =====================================================================

CREATE EXTENSION IF NOT EXISTS pgcrypto;

CREATE TABLE IF NOT EXISTS refresh_token_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID DEFAULT gen_random_uuid() NOT NULL,
    family_id VARCHAR(64) NOT NULL,
    token_hash VARCHAR(64) NOT NULL,
    access_token_jti VARCHAR(64),
    user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
    admin_id BIGINT REFERENCES admin(id) ON DELETE CASCADE,
    expires_at TIMESTAMPTZ NOT NULL,
    family_expires_at TIMESTAMPTZ NOT NULL,
    revoked BOOLEAN NOT NULL DEFAULT false,
    revoked_at TIMESTAMPTZ,
    revoked_reason VARCHAR(64),
    replaced_by_hash VARCHAR(64),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    created_by VARCHAR(255) NOT NULL DEFAULT 'SYSTEM',
    updated_by VARCHAR(255) NOT NULL DEFAULT 'SYSTEM',
    CONSTRAINT chk_rts_exactly_one_owner CHECK (
        (user_id IS NOT NULL AND admin_id IS NULL) OR
        (user_id IS NULL AND admin_id IS NOT NULL)
    )
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_rts_token_hash ON refresh_token_sessions(token_hash);
CREATE UNIQUE INDEX IF NOT EXISTS idx_rts_public_id ON refresh_token_sessions(public_id);
CREATE INDEX IF NOT EXISTS idx_rts_family_id ON refresh_token_sessions(family_id);
CREATE INDEX IF NOT EXISTS idx_rts_access_token_jti ON refresh_token_sessions(access_token_jti);
CREATE INDEX IF NOT EXISTS idx_rts_user_id ON refresh_token_sessions(user_id);
CREATE INDEX IF NOT EXISTS idx_rts_admin_id ON refresh_token_sessions(admin_id);
CREATE INDEX IF NOT EXISTS idx_rts_expires_at ON refresh_token_sessions(expires_at);
