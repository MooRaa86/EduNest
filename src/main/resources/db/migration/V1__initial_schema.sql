create table admin (
        created_at timestamp(6) not null,
        id bigint generated by default as identity,
        role_id bigint,
        updated_at timestamp(6) not null,
        created_by varchar(255) not null,
        email varchar(255),
        first_name varchar(255),
        headline varchar(255),
        last_name varchar(255),
        password varchar(255),
        profile_picture varchar(255),
        updated_by varchar(255) not null,
        primary key (id)
    );

    create table admin_badges (
        created_at timestamp(6) not null,
        id bigint generated by default as identity,
        updated_at timestamp(6) not null,
        created_by varchar(255) not null,
        description TEXT not null,
        name varchar(255) not null,
        type varchar(255) not null check (type in ('TOP_MENTOR','ACADEMIC_EXCELLENCE','COMMUNITY_LEADER','INNOVATOR_AWARD')),
        updated_by varchar(255) not null,
        primary key (id)
    );

    create table admin_notification (
        admin_id bigint,
        created_at timestamp(6) not null,
        id bigint generated by default as identity,
        updated_at timestamp(6) not null,
        content varchar(700),
        created_by varchar(255) not null,
        title varchar(255),
        type varchar(255) check (type in ('ANNOUNCEMENT','QUIZ','SESSION','TASK','PROJECT','SUPPORT','BADGE','CERTIFICATE','LIVE_SESSION','MENTORSHIP','REVIEW')),
        updated_by varchar(255) not null,
        primary key (id)
    );

    create table badge_awards (
        awarded_by bigint not null,
        badge_id bigint not null,
        created_at timestamp(6) not null,
        id bigint generated by default as identity,
        student_id bigint not null,
        updated_at timestamp(6) not null,
        created_by varchar(255) not null,
        note TEXT,
        updated_by varchar(255) not null,
        primary key (id),
        unique (badge_id, student_id)
    );

    create table badges (
        points integer not null check ((points<=500) and (points>=1)),
        created_at timestamp(6) not null,
        id bigint generated by default as identity,
        mentorship_id bigint not null,
        updated_at timestamp(6) not null,
        category varchar(255) not null check (category in ('ACHIEVEMENT','PERFORMANCE','CONSISTENCY','PROBLEM_SOLVING','CREATIVITY','LEADERSHIP','COMMUNITY','SPECIAL_RECOGNITION')),
        created_by varchar(255) not null,
        description TEXT not null,
        title varchar(255) not null,
        updated_by varchar(255) not null,
        primary key (id)
    );

    create table certificates (
        created_at timestamp(6) not null,
        id bigint generated by default as identity,
        issued_at timestamp(6) not null,
        mentorship_id bigint not null,
        student_id bigint not null,
        student_rank bigint not null,
