CREATE TABLE mentorship_completion_job (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mentorship_id bigint NOT NULL UNIQUE REFERENCES mentorship(id),
    actor_email varchar(255) NOT NULL,
    mentorship_title varchar(255) NOT NULL,
    mentor_name varchar(510) NOT NULL,
    snapshot_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    cohort_size bigint NOT NULL CHECK (cohort_size >= 0),
    stage varchar(20) NOT NULL DEFAULT 'CERTIFICATES'
        CHECK (stage IN ('CERTIFICATES', 'NOTIFICATIONS', 'DONE')),
    state varchar(20) NOT NULL DEFAULT 'PENDING'
        CHECK (state IN ('PENDING', 'RUNNING', 'RETRY', 'EXHAUSTED', 'DONE')),
    attempt_count integer NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    next_attempt_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    claim_token uuid,
    claim_generation bigint NOT NULL DEFAULT 0 CHECK (claim_generation >= 0),
    lease_until timestamptz,
    last_error varchar(2000),
    reconciled_at timestamptz,
    reconciled_by varchar(255),
    reconciliation_reason varchar(1000),
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CHECK ((state = 'DONE') = (stage = 'DONE')),
    CHECK ((state = 'RUNNING' AND claim_token IS NOT NULL AND lease_until IS NOT NULL)
        OR (state <> 'RUNNING' AND claim_token IS NULL AND lease_until IS NULL)),
    CHECK ((reconciled_at IS NULL AND reconciled_by IS NULL AND reconciliation_reason IS NULL)
        OR (reconciled_at IS NOT NULL AND reconciled_by IS NOT NULL AND reconciliation_reason IS NOT NULL))
);

CREATE INDEX idx_completion_job_due ON mentorship_completion_job (next_attempt_at, id)
    WHERE state IN ('PENDING', 'RETRY');
CREATE INDEX idx_completion_job_expired_lease ON mentorship_completion_job (lease_until, id)
    WHERE state = 'RUNNING';

CREATE TABLE mentorship_completion_snapshot (
    job_id bigint NOT NULL REFERENCES mentorship_completion_job(id),
    student_id bigint NOT NULL REFERENCES users(id),
    recipient_email varchar(255) NOT NULL,
    was_enrolled boolean NOT NULL,
    points_at_completion integer,
    student_rank bigint,
    cohort_size bigint,
    PRIMARY KEY (job_id, student_id),
    CHECK ((points_at_completion IS NULL AND student_rank IS NULL AND cohort_size IS NULL)
        OR (points_at_completion IS NOT NULL
            AND student_rank IS NOT NULL AND cohort_size IS NOT NULL
            AND student_rank > 0 AND cohort_size > 0 AND student_rank <= cohort_size))
);
CREATE UNIQUE INDEX uk_completion_snapshot_rank ON mentorship_completion_snapshot (job_id, student_rank)
    WHERE student_rank IS NOT NULL;
